// builtin_types.go 生成面板的兜底供应商元数据。
//
// 面板正常从 /panel/api/omni/provider-types 读取描述符，仅在该请求失败时使用
// 本文件生成的静态副本。副本由 catalog 生成而非手写，避免两套 schema 漂移
// （历史上兜底副本与描述符已经不一致：多出的字段、旧的 account_mode 词汇等）。
package panel

import (
	"encoding/json"
	"fmt"

	"github.com/wuxianggujun/omnigate-panel/internal/omnigate/plugin/catalog"
)

// builtinTypesPath 是生成产物在 web/ 下的路径。
const builtinTypesPath = "js/core/builtin-types.generated.js"

//go:generate go run ../../cmd/gen-panel-types

// BuiltinTypesJS 返回兜底元数据的 ESM 内容。它与 provider-types 接口返回的
// JSON 完全同形（catalog 描述符数组），面板用同一个 normalizeProviderTypes
// 解析，因此两条路径不会出现结构差异。
func BuiltinTypesJS() ([]byte, error) {
	raw, err := json.Marshal(catalog.All())
	if err != nil {
		return nil, fmt.Errorf("marshal builtin provider types: %w", err)
	}
	return []byte("// Code generated by go generate ./internal/panel; DO NOT EDIT.\n\n" +
		"export const BUILTIN_DESCRIPTORS = Object.freeze(" + string(raw) + ");\n"), nil
}
